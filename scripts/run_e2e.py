"""End-to-end evaluation: retrieval -> services -> LLM picks the tool (paper Table 2).

Scoring follows the authors' code:
  single-service: correct if the FIRST tool the LLM calls is the gold tool (Top-1: LLM sees top-1 service)
  multi-service:  correct if ALL gold tools are among the tools called (Top-3: LLM sees top-3 services)
AvgTokens = tokens generated by the LLM (paper Eq. 20), averaged over queries.

Example (Colab):
  export LLM_API_KEY=gsk_...
  python scripts/run_e2e.py --method flat --split single --k 1 --model qwen/qwen3.8-27b
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from hirag.data import load_mcpbench                    # noqa: E402
from hirag.dense import Embedder                        # noqa: E402
from hirag.llm import PROMPT_EN, PROMPT_ZH, DailyLimitError, LLMClient   # noqa: E402
from hirag.selectors import make_selector               # noqa: E402
from hirag.stage1 import Stage1, Stage1Config           # noqa: E402
from hirag.tools_schema import functions_for_services   # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--method", required=True, choices=["full", "flat", "colbert", "stage1", "hirag"])
    ap.add_argument("--split", default="single", choices=["single", "multi"])
    ap.add_argument("--k", type=int, default=None, help="services given to the LLM (default 1 single / 3 multi)")
    ap.add_argument("--model", default="qwen/qwen3.8-27b", help="Groq retired qwen3-32b on 2026-07-17")
    ap.add_argument("--provider", default=None, help="groq | xai | openrouter (auto from key)")
    ap.add_argument("--base-url", default=None)
    ap.add_argument("--prompt", default="zh", choices=["zh", "en"])
    ap.add_argument("--extra-body", default='{"reasoning_effort": "none", "reasoning_format": "hidden"}',
                    help="JSON passed to the API; Groq Qwen: disable thinking, hide reasoning (needed with tools)")
    ap.add_argument("--embed-model", default="BAAI/bge-large-en")
    ap.add_argument("--embed-backend", default="st", choices=["st", "onnx"])
    ap.add_argument("--colbert-model", default="BAAI/bge-large-en-v1.5")
    ap.add_argument("--tokenizer", default="jieba")
    ap.add_argument("--stage2", default=None, help="trained Stage 2 weights (.pt) for --method hirag")
    ap.add_argument("--max-turns", type=int, default=None, help="default 1 single / 4 multi")
    ap.add_argument("--max-tokens", type=int, default=256,
                    help="max generated tokens per call; a tool call needs ~50-150. Must be below the plan's OTPM limit")
    ap.add_argument("--min-interval", type=float, default=None,
                    help="seconds between calls; default = 60*max_tokens/otpm (stays under the output-tokens-per-minute limit)")
    ap.add_argument("--otpm", type=int, default=1000, help="your plan's output-tokens-per-minute limit (Groq free: 1000)")
    ap.add_argument("--limit", type=int, default=None, help="only the first N queries (quick test)")
    ap.add_argument("--cache", default="data/llm_cache.jsonl")
    ap.add_argument("--out-dir", default="results")
    a = ap.parse_args()

    k = a.k or (1 if a.split == "single" else 3)
    max_turns = a.max_turns or (1 if a.split == "single" else 4)
    bench = load_mcpbench()
    queries = (bench.single if a.split == "single" else bench.multi)[: a.limit]

    stage1 = colbert = reranker = None
    if a.method in ("flat", "stage1", "hirag"):
        emb = Embedder(a.embed_model, a.embed_backend)
        stage1 = Stage1(bench, emb, Stage1Config(tokenizer=a.tokenizer))
        stage1.precompute_dense([q.text for q in queries])
    if a.method == "hirag":
        if not a.stage2:
            ap.error("--method hirag needs --stage2 <weights.pt> (from scripts/train_stage2.py)")
        from hirag.stage2 import Stage2Reranker
        reranker = Stage2Reranker.load(a.stage2, bench, emb)
        reranker.precompute([q.text for q in queries])
    if a.method == "colbert":
        from hirag.colbert import ColBERTRetriever
        colbert = ColBERTRetriever([t.summary for t in bench.tools], a.colbert_model)
    select = make_selector(a.method, bench, stage1, colbert, reranker)

    llm = LLMClient(a.model, provider=a.provider, base_url=a.base_url, cache_path=a.cache,
                    extra_body=json.loads(a.extra_body), max_tokens=a.max_tokens,
                    min_interval=a.min_interval if a.min_interval is not None else 60.0 * a.max_tokens / a.otpm)
    prompt = PROMPT_ZH if a.prompt == "zh" else PROMPT_EN

    rows, correct, gen_tokens, prompt_tokens, svc_hit = [], 0, 0, 0, 0
    t0 = time.time()
    stopped = None
    for n, q in enumerate(queries, 1):
        services = select(q.text, k)
        try:
            res = llm.select_tools(q.text, functions_for_services(bench, services), prompt, max_turns)
        except DailyLimitError as e:
            stopped = str(e)
            print(f"\nDAILY LIMIT reached at query {n}/{len(queries)}:\n  {stopped}\n"
                  "Partial results saved below. Re-run this same cell later (tomorrow): finished queries "
                  "come from the cache instantly.", flush=True)
            break
        svc_hit += all(g in services for g in q.gold_services)
        called = [c.lower() for c in res.tool_calls]
        if q.kind == "single":
            ok = bool(called) and called[0] == q.gold_tools[0]
        else:
            ok = all(g in called for g in q.gold_tools)
        correct += ok
        gen_tokens += res.completion_tokens
        prompt_tokens += res.prompt_tokens
        rows.append({"qid": q.qid, "query": q.text, "services": services, "gold": q.gold_tools,
                     "called": called, "correct": ok, "completion_tokens": res.completion_tokens,
                     "prompt_tokens": res.prompt_tokens, "error": res.error})
        if n % 10 == 0 or n == len(queries):
            print(f"[{n}/{len(queries)}] acc {100*correct/n:.1f}%  ({time.time()-t0:.0f}s)", flush=True)

    n = len(rows)
    if n == 0:
        print("No queries finished; nothing saved.")
        return
    summary = {"complete": stopped is None, "n_total": len(queries),"method": a.method, "split": a.split, "k": k, "model": a.model, "n": n,
               "accuracy": 100 * correct / n, "gold_services_given": 100 * svc_hit / n,
               "avg_generated_tokens": gen_tokens / n, "avg_prompt_tokens": prompt_tokens / n,
               "embed_model": a.embed_model if stage1 else None, "prompt": a.prompt}
    print(json.dumps(summary, indent=2))
    os.makedirs(a.out_dir, exist_ok=True)
    tag = f"e2e_{a.method}_{a.split}_k{k}_{a.model.replace('/', '-')}" + ("" if stopped is None else "_PARTIAL")
    json.dump({"summary": summary, "rows": rows}, open(os.path.join(a.out_dir, tag + ".json"), "w"),
              indent=1, ensure_ascii=False)
    print("saved", os.path.join(a.out_dir, tag + ".json"))


if __name__ == "__main__":
    main()
